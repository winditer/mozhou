/**
 * AI 味的规则本体 —— 放在 shared 而不是 renderer，是因为它现在要被两处同时使用：
 *
 *   1. **渲染进程**：选区「去 AI 味」按钮、全书去 AI 味面板、技法卡注入
 *   2. **主进程**：技法卡的种子数据（内置卡直接引用 DE_AI_GENERATE_HINT）
 *
 * 主进程不能引 renderer。之前规则放在 renderer/lib/textcraft.ts，种子卡一引用
 * 就跨了边界。而复制一份是最坏的选择——那正是 textcraft 里警告过的「两边分叉」：
 * 同一段文字从选区走一遍和从体检走一遍，改出来的手感就会不一样。
 *
 * 所以规则上移到 shared，textcraft.ts 只做 re-export，既有 import 全部不用改。
 *
 * 这一层的立场：AI 味不是靠「降低温度」能去掉的，它是一组具体的坏习惯。
 * 所以这里不写「请写得自然一点」，而是把坏习惯一条条列成可执行的禁令，并给出反例。
 */

/**
 * 六条禁令的**本体**，不含任何「改写」措辞。
 *
 * 同一批坏习惯要出现在两个完全不同的场景里：
 * 一是**改写**（选区按钮、全书去 AI 味面板），语气是「把这段改掉」；
 * 二是**生成**（技法卡在写正文时预先约束），语气是「不要这么写」。
 *
 * 如果两份各写一遍，作者会发现同一段文字「生成时说要避开」和「体检时说要改掉」
 * 措辞不一样，进而怀疑标准不一致。所以禁令只写一份，两侧各自拼头尾。
 * **任何新增/修改禁令都只改这里**，别在下面两个常量里复制条款。
 */
export const DE_AI_RULES = `- 删掉所有替读者下结论的句子（动作或对话后面紧跟的心理注解、"他终于明白了""这一刻她忽然意识到""某种说不清的情绪"），让前面的动作自己说话。
- 清掉解释性副词与万能形容词："不禁""不由得""仿佛""似乎""微微""缓缓""深深地""莫名地"，一律先删；删掉后读不通，说明原本写虚了，改写成具体动作。
- 句子长度必须长短相间。AI 偏爱等长句子和平行排比，至少拆掉三分之一的复句，允许出现三五个字的短句。
- 用具体名词替换抽象名词：不写"一种复杂的情绪"，写"她把勺子放回碗里，没吃完"。
- 对话按人说话的样子写：允许答非所问、打断、停顿，不许用台词交代设定。
- 段末禁止升华、点题、暗示"这一切才刚开始"。最后一句写完就停。`

/**
 * 改写场景的完整指令：选区「去 AI 味」按钮与全书去 AI 味面板共用这一份。
 * 两块都从这里取，谁都不许自己拼一份。
 */
export const DE_AI_INSTRUCTION = `改写选中文字，去掉机器味。这不是润色，是治病，请严格按下面六条执行，宁可改得粗糙也不要留一句总结腔：

${DE_AI_RULES}

保持原意与情节信息，只输出改写后的正文，不要任何说明或前后对比。`

/**
 * 生成场景的指令：写正文时**预先**避开这些坏习惯。
 *
 * 用「偏好」而不是「禁令」的语气，是因为这是软约束：写小说时偶尔一个「仿佛」
 * 并无问题，硬禁会让模型为了躲词把句子写紧、写僵，反而丢掉原本的表现力。
 * 所以这里只说「尽量」，并把追责交给全书去 AI 味的本地检测兜底——
 * 那一层是逐条可数的，能兜住这里漏掉的部分；反过来则做不到。
 */
export const DE_AI_GENERATE_HINT = `写作时请尽量避开下面这些机器腔的坏习惯（是偏好，不是硬禁令——偶尔一处无妨，成片出现才算毛病）：

${DE_AI_RULES}

总的原则：宁可写得粗糙具体，也不要写得圆滑空泛。`